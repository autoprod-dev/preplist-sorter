// r14: xlsx upload (handleFile path), paste, sample menu — loader + no persistence.
import http from 'http'; import fs from 'fs'; import path from 'path'; import { fileURLToPath } from 'url'; import { chromium } from 'playwright';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const XLSX = process.env.XLSX || '/workspace/paula-WE-15.11.26-For-Sorter.xlsx';
const MIME = { '.html':'text/html','.js':'text/javascript','.mjs':'text/javascript','.css':'text/css','.json':'application/json','.png':'image/png' };
const server = http.createServer((q,r)=>{let u=decodeURIComponent(q.url.split('?')[0]);if(u.endsWith('/'))u+='index.html';const fp=path.join(ROOT,u);if(!fp.startsWith(ROOT)||!fs.existsSync(fp)||fs.statSync(fp).isDirectory()){r.writeHead(404);r.end();return;}r.writeHead(200,{'Content-Type':MIME[path.extname(fp)]||'application/octet-stream'});fs.createReadStream(fp).pipe(r);});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1366, height: 900 } });
const errs = []; p.on('pageerror', e => errs.push(String(e)));
let pass = 0, fail = 0; const ck = (n, c, d) => { c ? pass++ : fail++; console.log(c ? '[PASS]' : '[FAIL]', n, d || ''); };
await p.goto(`http://127.0.0.1:${server.address().port}/index.html`);
await p.waitForFunction(() => window.__preplineBridge && window.PreplineUiR14 && !PreplineUiR14.isOn(), null, { timeout: 30000 });
await p.evaluate(() => { window.__seen = 0; const L = document.getElementById('plLoader'); new MutationObserver(() => { if (L.classList.contains('on')) window.__seen++; }).observe(L, { attributes: true }); });
await p.setInputFiles('#fileInput', XLSX);
await p.waitForSelector('#sbChoice.open', { timeout: 60000 });
await p.waitForTimeout(400);
ck('loader yields to "Spreadsheet ready" choice', await p.evaluate(() => !PreplineUiR14.isOn()));
await p.click('#sbChoice >> text=Sort now');
await p.waitForFunction(() => __preplineBridge.getRows().length > 5, null, { timeout: 60000 });
await p.waitForFunction(() => !PreplineUiR14.isOn(), null, { timeout: 30000 });
const x = await p.evaluate(() => ({ rows: __preplineBridge.getRows().length, seen: window.__seen, status: document.getElementById('statusMsg').textContent.slice(0, 120) }));
ck('xlsx sorted', x.rows > 5, JSON.stringify(x));
ck('xlsx loader shown + hidden', x.seen >= 1);
await p.evaluate(() => { const oc = document.getElementById('outputChoice'); if (oc) oc.hidden = true; });
await p.evaluate(() => { document.getElementById('pasteBox').value = 'Test Dish\tCarrot batons\t50\tg\nTest Dish\tBeef fillet\t180\tg'; });
await p.evaluate(() => document.getElementById('parsePasteBtn').click());
await p.waitForTimeout(800);
const y = await p.evaluate(() => ({ rows: __preplineBridge.getRows().length, on: PreplineUiR14.isOn() }));
ck('paste sorted', y.rows === 2, JSON.stringify(y));
ck('paste loader cleared', !y.on);
p.on('dialog', d => d.accept());
await p.evaluate(() => loadSampleMenu());
await p.waitForTimeout(800);
const z = await p.evaluate(() => __preplineBridge.getRows().length);
ck('sample menu loads', z > 5, String(z));
const ls = await p.evaluate(() => { const a = []; for (let i = 0; i < localStorage.length; i++) a.push(localStorage.key(i)); return a; });
ck('no upload keys persisted', !ls.some(k => /DishDatabase|OnetimeSession|pos\.v1|poLinks|snapshot|recipes\.v1|organised\.staff|tickoff|undo/.test(k)), ls.join(','));
ck('no page errors', errs.length === 0, errs.join(' | '));
await b.close(); server.close(); console.log('RESULT', pass, '/', pass + fail); if (fail) process.exit(1);
